# Builds the one-shot launch SQL for the live database from the source files.
# Run: python3 live/build.py  (from mdp/supabase). Demo-only sample data is left out.
import re
src = lambda f: open(f).read()
da = src('dupr_access.sql'); da = da[:da.index('-- Demo: DUPR Demo needs a DUPR account')]
bw = src('booking_windows.sql'); bw = bw[:bw.index('select key, value')]
tr = src('tournaments.sql')
tdupr = tr[tr.index('-- A player\'s DUPR standing'):tr.index('create or replace function _t_organizer')]
parts = [
  ('Court board, and hosts running their own sessions', src('court_board.sql')),
  ('DUPR standing', tdupr + "revoke all on function _t_dupr(uuid) from public, anon, authenticated;\n"),
  ('DUPR access (off until production DUPR: dupr_gate)', da),
  ("Court groups (Chris's format)", src('groups.sql')),
  ('Overpayments', src('admin.sql')),
  ('Members screen', src('members.sql')),
  ('Coaching: the app collects only the club share', src('training_club_only.sql')),
  ('Booking windows: Varsity 2 weeks, Member 5 days, Community 3 days, Flagged 1 hour', bw),
]
head = """-- MDP app v2 launch: everything the new app needs on the live database, in one go.
-- Generated by live/build.py from the source files (demo-only sample data left out). Safe to run twice.
-- The old app keeps working, except that its DUPR-night board is replaced by the new one.
--
-- DUPR rules stay off until production DUPR is connected:
--   update app_config set value = 'on' where key = 'dupr_gate';
--   update app_config set value = 'prod' where key = 'dupr_env';

insert into app_config (key, value) values ('dupr_gate', 'off') on conflict (key) do nothing;
"""
out = head + ''.join(f'\n-- ── {t} ──\n{b}\n' for t, b in parts)
open('live/2026-11-14_app_v2.sql', 'w').write(out)
print(len(out.splitlines()), 'lines')
